#!/usr/bin/env python3
# Module: mirante.tools.camera_table
# Purpose: Generates crates/mirante-raw/src/camera_table.rs from dcraw's adobe_coeff table.
# Created: 2026-11-16
# Architecture: Reads dcraw.c as text (never compiles or runs it) and writes the
# prefix, black, maximum and 12 matrix numbers of each entry, in dcraw's order,
# because lookup takes the first matching prefix.
# Usage: tools/camera_table.py path/to/dcraw.c [output.rs]

import pathlib
import re
import sys

DEFAULT_OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "crates/mirante-raw/src/camera_table.rs"
ENTRY = re.compile(r'\{\s*"([^"]+)"\s*,\s*([-\w]+)\s*,\s*([-\w]+)\s*,\s*\{([^}]*)\}\s*\}')
HEADER = """\
//! Module: mirante_raw::camera_table
//! Purpose: Per-camera XYZ (D65) to camera matrices (x 1/10000), black and maximum.
//! Created: 2026-11-16
//! Architecture: Generated by tools/camera_table.py; do not edit by hand. Colour
//! matrices from dcraw by Dave Coffin, adobe_coeff table (dcraw.c, 2018). Order
//! matters: camera.rs takes the first entry whose prefix matches "<make> <model>".

/// One adobe_coeff row; zero black or maximum means "not given".
pub struct CameraEntry {
    pub prefix: &'static str,
    pub black: u16,
    pub maximum: u16,
    pub matrix: [i16; 12],
}

const fn entry(prefix: &'static str, black: u16, maximum: u16, matrix: [i16; 12]) -> CameraEntry {
    CameraEntry { prefix, black, maximum, matrix }
}

#[rustfmt::skip]
pub static CAMERAS: &[CameraEntry] = &[
"""


def table_source(dcraw: str) -> str:
    start = dcraw.index("void CLASS adobe_coeff")
    body = dcraw.index("table[] = {", start)
    end = dcraw.index("\n  };", body)
    return re.sub(r"/\*.*?\*/", "", dcraw[body:end], flags=re.S)


def entries(source: str):
    for prefix, black, maximum, numbers in ENTRY.findall(source):
        matrix = [int(n, 0) for n in numbers.replace("\n", " ").split(",") if n.strip()]
        if len(matrix) > 12:
            raise ValueError(f"{prefix}: more than 12 matrix numbers")
        yield prefix, int(black, 0), int(maximum, 0), matrix + [0] * (12 - len(matrix))


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit("usage: camera_table.py path/to/dcraw.c [output.rs]")
    dcraw = pathlib.Path(sys.argv[1]).read_text(encoding="latin-1")
    output = pathlib.Path(sys.argv[2]) if len(sys.argv) == 3 else DEFAULT_OUTPUT
    rows = list(entries(table_source(dcraw)))
    if not rows:
        sys.exit("no adobe_coeff entries found")
    lines = [HEADER]
    for prefix, black, maximum, matrix in rows:
        numbers = ", ".join(str(n) for n in matrix)
        lines.append(f'    entry("{prefix}", {black}, {maximum}, [{numbers}]),\n')
    lines.append("];\n")
    output.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} cameras to {output}")


if __name__ == "__main__":
    main()
